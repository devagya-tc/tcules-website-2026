#!/usr/bin/env node
/**
 * Measure every image the `_pages/` corpus binds, and write the registry a page reads.
 *
 *   npm run corpus:assets            fetch each bound asset, write src/lib/corpus-assets.generated.ts
 *   npm run corpus:assets -- --check exit 1 if a bound asset is missing from the registry; no network
 *
 * Why it exists. The frontmatter binds an asset by URL only (`asset_uri`), and an image record needs
 * its intrinsic width and height: Media reserves the box from them before the file lands, and the
 * photograph resolution rule (visual-direction § 5.4) is a comparison against them. Nothing in the
 * corpus says them, so they are measured once here, from the file Cloudinary serves, and committed.
 *
 * The registry is keyed by the URL exactly as authored. `corpus:assets -- --check` is the gate a new
 * binding cannot pass until this has run, so a page never renders an image of unknown size.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

import * as prettier from 'prettier';

const require = createRequire(import.meta.url);
const sharp = require('sharp');

const PAGES = '_pages';
const OUT = 'src/lib/corpus-assets.generated.ts';
const check = process.argv.includes('--check');

const urls = new Set();
for (const file of readdirSync(PAGES).filter((f) => f.endsWith('.md'))) {
  const text = readFileSync(join(PAGES, file), 'utf8');
  /* Only the frontmatter binds assets, and an `asset_uri` line is how it does it. */
  for (const match of text.matchAll(/^\s*asset_uri:\s*(https?:\/\/\S+)\s*$/gm))
    urls.add(match[1]);
}
const wanted = [...urls].sort();

const existing = new Map();
if (existsSync(OUT)) {
  const source = readFileSync(OUT, 'utf8');
  for (const m of source.matchAll(
    /'([^']+)':\s*\{\s*width:\s*(\d+),\s*height:\s*(\d+)\s*\}/g,
  )) {
    existing.set(m[1], { width: Number(m[2]), height: Number(m[3]) });
  }
}

if (check) {
  const missing = wanted.filter((u) => !existing.has(u));
  if (missing.length) {
    console.error(`corpus:assets — ${missing.length} bound asset(s) not measured:`);
    for (const u of missing) console.error(`  ${u}`);
    console.error('run `npm run corpus:assets`');
    process.exit(1);
  }
  console.log(`corpus:assets — ${wanted.length} bound assets, all measured`);
  process.exit(0);
}

const sizes = new Map();
for (const url of wanted) {
  const known = existing.get(url);
  if (known) {
    sizes.set(url, known);
    continue;
  }
  const res = await fetch(url);
  if (!res.ok) {
    console.error(`FAIL  ${res.status} ${url}`);
    process.exit(1);
  }
  const meta = await sharp(Buffer.from(await res.arrayBuffer())).metadata();
  if (!meta.width || !meta.height) {
    console.error(`FAIL  no dimensions ${url}`);
    process.exit(1);
  }
  sizes.set(url, { width: meta.width, height: meta.height });
  console.log(`measured ${meta.width} x ${meta.height}  ${url}`);
}

const body = [...sizes.entries()]
  .map(([url, { width, height }]) => `  '${url}': { width: ${width}, height: ${height} },`)
  .join('\n');

const source = `/**
 * GENERATED by scripts/corpus-assets.mjs. Do not edit.
 *
 * The intrinsic size of every image the \`_pages/\` corpus binds (\`asset_uri\`), keyed by the URL as
 * authored. Read by \`corpusImage\` (src/lib/corpus-images.ts).
 */
export const CORPUS_ASSET_SIZES: Readonly<Record<string, { width: number; height: number }>> = {
${body}
};
`;

writeFileSync(OUT, await prettier.format(source, { parser: 'typescript', singleQuote: true }));
console.log(`corpus:assets — wrote ${sizes.size} assets to ${OUT}`);
