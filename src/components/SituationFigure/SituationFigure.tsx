import { SITUATION_FIGURES, type SituationFigureName } from './figures.generated';
import styles from './SituationFigure.module.css';

export type { SituationFigureName };

export type SituationFigureProps = {
  name: SituationFigureName;
  /**
   * Which state to show. Omitted, the drawing rests and plays to its end when the link it sits in
   * is hovered or focused. `end` holds the end state — for a specimen showing both.
   */
  state?: 'end';
  /**
   * Keeps the drawing's clip and mask ids unique when the same drawing appears twice on one page
   * (a specimen's rest and end). Omit where each drawing appears once.
   */
  instance?: string;
};

/** True when a name (a service route's scene, for instance) has a situation drawing. */
export const isSituationFigureName = (name: string): name is SituationFigureName =>
  name in SITUATION_FIGURES;

/**
 * TIER 1 — SituationFigure. One of the home gateway's six isometric drawings (owner, round 11,
 * 19 Oct 2026), each telling its situation in two states: rest shows the problem, end shows it
 * solved. Hovering or focusing the link it sits in plays rest → end as ONE motion — every moving
 * part on the same duration and curve — and leaving plays it back.
 *
 * The drawings are generated (scripts/illustrations/situations.mjs → figures.generated.ts) in the
 * Reasons house style and shared one viewBox, so all six sit at one scale. They are inline SVG,
 * not images, because the motion is in their parts. Decorative: aria-hidden; the words beside the
 * drawing carry the meaning. Drawn for the paper ground only.
 */
export function SituationFigure({ name, state, instance }: SituationFigureProps) {
  const figure = SITUATION_FIGURES[name];
  const id = `sfig-${name}${instance ? `-${instance}` : ''}`;
  return (
    <svg
      className={styles.figure}
      viewBox={figure.viewBox}
      aria-hidden="true"
      focusable="false"
      data-state={state}
      // Generated by the repo's own script from the illustration kit; never user content.
      dangerouslySetInnerHTML={{ __html: figure.markup.replaceAll('{{id}}', id) }}
    />
  );
}
